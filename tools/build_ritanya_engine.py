"""
Generates assets/ritanya/engine.js: the browser-side copy of Ritanya's deterministic matcher.

Source of truth stays in Python (app/ritanya_knowledge.py and app/ritanya_chat.py). This script reads the knowledge, the
destinations and EVERY matching pattern straight from those modules and writes them into the JavaScript file as data, so
nothing is transcribed by hand. Only the small decision procedure (the order of the checks) is written here, in JS_LOGIC,
and tests/test_ritanya_engine_parity.py compares it with the Python implementation across a large corpus.

    python tools/build_ritanya_engine.py          # rewrites assets/ritanya/engine.js
    python tools/build_ritanya_engine.py --check  # exits 1 if the committed file is out of date

tests/test_ritanya_engine_parity.py runs the --check logic, so a knowledge or pattern change without a regenerated file
fails the build. (tools/ is not deployed; assets/ritanya/engine.js is.)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import ritanya_chat as rc  # noqa: E402
from app import ritanya_knowledge as K  # noqa: E402

TARGET = ROOT / "assets" / "ritanya" / "engine.js"


def data():
    d = K.DESTINATIONS
    return {
        "canonicalHost": K.CANONICAL_HOST,
        "scope": rc.SCOPE,
        "limits": {"maxMessageChars": rc.MAX_MESSAGE_CHARS, "maxUnknownStreak": rc.MAX_UNKNOWN_STREAK},
        "destinations": {k: {"label": v.label, "path": v.path, "needs_sign_in": v.needs_sign_in} for k, v in d.items()},
        "topics": {t.id: {"reply": t.reply, "more": t.more, "actions": list(t.actions), "suggestions": list(t.suggestions)} for t in K.TOPICS.values()},
        "text": {
            "refusePersonal": K.REFUSE_PERSONAL, "refusePersonalActions": list(K.REFUSE_PERSONAL_ACTIONS),
            "refusePersonalSuggestions": list(K.REFUSE_PERSONAL_SUGGESTIONS),
            "refuseOutOfBounds": K.REFUSE_OUT_OF_BOUNDS,
            "noAccountAccess": K.NO_ACCOUNT_ACCESS, "noAccountAccessActions": list(K.NO_ACCOUNT_ACCESS_ACTIONS),
            "greeting": K.GREETING, "thanks": K.THANKS, "clarify": K.CLARIFY, "clarifySuggestions": list(K.CLARIFY_SUGGESTIONS),
            "unknown": K.UNKNOWN, "unknownRepeated": K.UNKNOWN_REPEATED, "unknownSuggestions": list(K.UNKNOWN_SUGGESTIONS),
            "noTopicForFollowup": K.NO_TOPIC_FOR_FOLLOWUP, "startSuggestions": list(K.START_SUGGESTIONS),
        },
        "patterns": {
            "control": rc._CONTROL.pattern,
            "hostlike": rc._HOSTLIKE.pattern, "injection": rc._INJECTION.pattern, "account": rc._ACCOUNT_DATA.pattern,
            "personal": [r.pattern for r in rc._PERSONAL],
            "topics": [[t, r.pattern] for t, r in rc._TOPIC_RULES],
            "greeting": rc._GREETING.pattern, "thanks": rc._THANKS.pattern, "vague": rc._VAGUE.pattern,
            "more": rc._MORE.pattern, "where": rc._WHERE.pattern,
        },
    }


JS_HEAD = """/* Ritanya browser engine. GENERATED by tools/build_ritanya_engine.py from app/ritanya_knowledge.py and app/ritanya_chat.py.
   DO NOT EDIT: change the Python source and regenerate. tests/test_ritanya_engine_parity.py fails if this file is out of date
   or if its answers differ from the Python matcher.

   What it is: the same fixed-answer matcher the server runs, so a message can be answered inside the visitor's browser.
   What it is not: it has no model, makes no network request, reads no storage, no cookie and no account. It takes a string
   and returns one of the reviewed answers; every link it can return is a relative path on rithavo.com from the list below. */
"""

JS_LOGIC = r"""
  function rx(p) { return new RegExp(p, "i"); }
  var CONTROL = new RegExp(D.patterns.control, "g");
  var P = {
    hostlike: rx(D.patterns.hostlike), injection: rx(D.patterns.injection), account: rx(D.patterns.account),
    personal: D.patterns.personal.map(rx),
    topics: D.patterns.topics.map(function (t) { return [t[0], rx(t[1])]; }),
    greeting: rx(D.patterns.greeting), thanks: rx(D.patterns.thanks), vague: rx(D.patterns.vague),
    more: rx(D.patterns.more), where: rx(D.patterns.where)
  };
  var T = D.text;

  function has(o, k) { return Object.prototype.hasOwnProperty.call(o, k); }
  function codePointLength(s) { var n = 0; for (var i = 0; i < s.length; i++) { var c = s.charCodeAt(i); if (c >= 0xD800 && c <= 0xDBFF && i + 1 < s.length) i++; n++; } return n; }

  // clean_message: NFC, control and zero-width characters to spaces, whitespace collapsed
  function clean(raw) {
    var text = raw.normalize("NFC").replace(CONTROL, " ");
    return text.replace(/\s+/g, " ").trim();
  }

  // _norm: lower-case, the company's own address becomes the company, anything but a-z 0-9 @ rupee whitespace and dots is a space
  function norm(message) {
    var text = message.toLowerCase().replace(/(?<![a-z0-9.\-])rithavo\.com/g, "rithavo");
    text = text.replace(/[^a-z0-9@₹\s.]/gu, " ");
    text = text.replace(/(?<![a-z0-9])\.|\.(?![a-z0-9])/g, " ");
    return text.replace(/\s+/g, " ").trim();
  }

  function action(key) {
    var d = D.destinations[key];
    return { id: key, label: d.label, href: d.path, canonical: D.canonicalHost + d.path, needs_sign_in: d.needs_sign_in };
  }
  function response(reply, o) {
    o = o || {};
    return {
      reply: reply, topic: o.topic === undefined ? null : o.topic,
      actions: (o.actions || []).map(action), suggestions: (o.suggestions || []).slice(),
      clarify: !!o.clarify, unknown: !!o.unknown, refused: !!o.refused,
      scope: D.scope, live_ai: false, _intent: o.intent || "answer"
    };
  }
  function topicResponse(id, more) {
    var t = D.topics[id];
    return response(more ? t.more : t.reply, { topic: id, actions: t.actions, suggestions: t.suggestions, intent: id + (more ? "_more" : "") });
  }

  // answer(): the same order of checks as app/ritanya_chat.py answer(); message must already be cleaned
  function answer(message, lastTopic, unknownStreak) {
    lastTopic = lastTopic || null; unknownStreak = unknownStreak || 0;
    var text = norm(message), i;
    if (P.injection.test(text) || P.hostlike.test(text)) return response(T.refuseOutOfBounds, { actions: ["about"], suggestions: T.startSuggestions, refused: true, intent: "out_of_bounds" });
    for (i = 0; i < P.personal.length; i++) {
      if (P.personal[i].test(text)) return response(T.refusePersonal, { topic: "career_intelligence", actions: T.refusePersonalActions, suggestions: T.refusePersonalSuggestions, refused: true, intent: "personal_refused" });
    }
    if (P.account.test(text)) return response(T.noAccountAccess, { actions: T.noAccountAccessActions, suggestions: T.startSuggestions, refused: true, intent: "account_access_refused" });
    if (P.greeting.test(text)) return response(T.greeting, { suggestions: T.startSuggestions, intent: "greeting" });
    if (P.thanks.test(text)) return response(T.thanks, { suggestions: T.startSuggestions, intent: "thanks" });
    for (i = 0; i < P.topics.length; i++) { if (P.topics[i][1].test(text)) return topicResponse(P.topics[i][0], false); }
    if (P.more.test(text)) return lastTopic ? topicResponse(lastTopic, true) : response(T.noTopicForFollowup, { suggestions: T.startSuggestions, clarify: true, intent: "followup_no_topic" });
    if (P.where.test(text)) return lastTopic ? topicResponse(lastTopic, false) : response(T.noTopicForFollowup, { suggestions: T.startSuggestions, clarify: true, intent: "followup_no_topic" });
    if (P.vague.test(text)) return response(T.clarify, { suggestions: T.clarifySuggestions, clarify: true, intent: "clarify" });
    var repeated = unknownStreak >= 1;
    return response(repeated ? T.unknownRepeated : T.unknown, { actions: repeated ? ["contact"] : [], suggestions: T.unknownSuggestions, unknown: true, intent: "unknown" });
  }

  // validate_payload: strict, never throws, never echoes. Returns {ok:true, data} or {ok:false, error}
  function validate(message, lastTopic, unknownStreak) {
    if (typeof message !== "string") return { ok: false, error: "invalid_request" };
    var m = clean(message), n = codePointLength(m);
    if (n < 1 || n > D.limits.maxMessageChars) return { ok: false, error: "invalid_request" };
    if (lastTopic !== undefined && lastTopic !== null && (typeof lastTopic !== "string" || !has(D.topics, lastTopic))) return { ok: false, error: "invalid_request" };
    var s = unknownStreak === undefined ? 0 : unknownStreak;   // like the server: absent means 0, null is invalid
    if (typeof s !== "number" || !isFinite(s) || Math.floor(s) !== s || s < 0 || s > D.limits.maxUnknownStreak) return { ok: false, error: "invalid_request" };
    return { ok: true, data: { message: m, last_topic: lastTopic === undefined ? null : lastTopic, unknown_streak: s } };
  }

  // respond(): validate then answer, exactly what the server's chat route does for one message
  function respond(message, lastTopic, unknownStreak) {
    var v = validate(message, lastTopic, unknownStreak);
    if (!v.ok) return { ok: false, error: v.error };
    var r = answer(v.data.message, v.data.last_topic, v.data.unknown_streak);
    delete r._intent;
    return { ok: true, result: r };
  }
"""


def render():
    payload = json.dumps(data(), ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    body = "(function (root) {\n  \"use strict\";\n  var D = " + payload + ";\n" + JS_LOGIC
    body += "\n  root.RitanyaEngine = { respond: respond, answer: answer, validate: validate, clean: clean, norm: norm, topics: Object.keys(D.topics) };\n"
    body += "})(typeof self !== \"undefined\" ? self : this);\n"
    return JS_HEAD + body


def main(argv):
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            print("assets/ritanya/engine.js is out of date: run python tools/build_ritanya_engine.py")
            return 1
        print("engine.js is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_bytes(text.encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
